export function computePss10Score(responses: number[]): {
  total: number;
  band: 'Low Perceived Stress' | 'Moderate Perceived Stress' | 'High Perceived Stress';
} {
  const total = PSS10_ITEMS.reduce((sum, item, idx) => {
    const raw = responses[idx] ?? 2;
    return sum + (item.reverseScored ? 4 - raw : raw);
  }, 0);
  const band =
    total <= 13
      ? 'Low Perceived Stress'
      : total <= 26
        ? 'Moderate Perceived Stress'
        : 'High Perceived Stress';
  return { total, band };
}

